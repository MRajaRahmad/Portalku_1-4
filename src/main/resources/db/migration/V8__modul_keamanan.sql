CREATE TABLE pengguna (
    id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email  VARCHAR(150) NOT NULL UNIQUE,
    sandi  VARCHAR(72)  NOT NULL,
    nama   VARCHAR(100) NOT NULL,
    peran  VARCHAR(10)  NOT NULL,
    aktif  BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE token_penyegar (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token       VARCHAR(255) NOT NULL UNIQUE,
    id_pengguna INTEGER      NOT NULL,
    kedaluwarsa TIMESTAMP    NOT NULL,
    dicabut     BOOLEAN      NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_token_pengguna
        FOREIGN KEY (id_pengguna)
        REFERENCES pengguna (id)
        ON DELETE CASCADE
);

CREATE INDEX idx_token_pengguna
    ON token_penyegar (id_pengguna);